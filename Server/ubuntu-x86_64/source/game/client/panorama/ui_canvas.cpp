static bool Helper_JSArrayToVector2Ds( int nPointCount, v8::Local<v8::Array> points, CUtlVector< Vector2D > &vPoints )
{
	if ( points->Length() % 2 )
		return false;

	Vector2D vP;

	vPoints.EnsureCapacity( nPointCount );

	for ( int i = 0; i < points->Length(); )
	{
		v8::Local<v8::Value> x, y;
		auto context = v8::Isolate::GetCurrent()->GetCurrentContext();
		if ( !points->Get( context, i ).ToLocal( &x ) || !points->Get( context, i + 1 ).ToLocal( &y ) || !x->IsNumber() || !y->IsNumber() )
			return false;

		vP.x = (float)x.As<v8::Number>()->Value();
		vP.y = (float)y.As<v8::Number>()->Value();

		vPoints.AddToTail( vP );

		i += 2;
	}

	return true;
}

static bool Helper_JSArrayToColors( int nPointCount, v8::Local<v8::Array> colors, CUtlVector< Color > &vColors )
{
	Color col;

	vColors.EnsureCapacity( nPointCount );

	for ( int i = 0; i < colors->Length(); i++ )
	{
		v8::Local<v8::Value> value;
		auto isolate = v8::Isolate::GetCurrent();
		if ( !colors->Get( isolate->GetCurrentContext(), i ).ToLocal( &value ) || !value->IsString() )
			return false;

		v8::String::Utf8Value szColor( isolate, value );

		if ( !CSSHelpers::BParseColor( &col, *szColor ) )
			col.SetColor( 0xff, 0xff, 0xff, 0xff );

		vColors.AddToTail( col );
	}
	
	return true;
}

