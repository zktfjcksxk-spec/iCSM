#define CANVAS_CIRCLE_POINT_COUNT 24
//-----------------------------------------------------------------------------
//-----------------------------------------------------------------------------
void CUI_Canvas::DrawFilledCircle( const Vector2D& vPos, float flRadius, const Color& drawColor )
{
	CUI_CanvasRenderer *pRenderer = m_pRenderer;
	if ( !pRenderer )
		return;

	EnqueueCommand( MakeDrawCommand(
		[ = ]( IMatRenderContext *pRenderContext )
	{
		int nNumTriangles = CANVAS_CIRCLE_POINT_COUNT;

		const float flUIScaleX = pRenderer->GetUIScaleX();
		const float flUIScaleY = pRenderer->GetUIScaleY();

		IMesh* m_pMesh = pRenderContext->GetDynamicMesh( true, NULL, NULL, pRenderer->m_WhiteMaterial );
		CMeshBuilder meshBuilder;
		meshBuilder.Begin( m_pMesh, MATERIAL_TRIANGLES, nNumTriangles * 3 );

		float x0 = pRenderer->GetUIScaleX() * vPos.x;
		float y0 = pRenderer->GetUIScaleX() * vPos.y;

		for ( int i = 0; i < nNumTriangles; ++i )
		{
			float x1 = pRenderer->GetUIScaleX() * ( vPos.x + flRadius * cos( i * 2 * M_PI / CANVAS_CIRCLE_POINT_COUNT ) );
			float y1 = pRenderer->GetUIScaleX() * ( vPos.y + flRadius * sin( i * 2 * M_PI / CANVAS_CIRCLE_POINT_COUNT ) );

			float x2 = pRenderer->GetUIScaleX() * ( vPos.x + flRadius * cos( (i+1) * 2 * M_PI / CANVAS_CIRCLE_POINT_COUNT ) );
			float y2 = pRenderer->GetUIScaleX() * ( vPos.y + flRadius * sin( (i+1) * 2 * M_PI / CANVAS_CIRCLE_POINT_COUNT ) );

			meshBuilder.Color4ub( drawColor.r(), drawColor.g(), drawColor.b(), drawColor.a() );
			meshBuilder.TexCoord2f( 0, 0.0f, 0.0f );
			meshBuilder.Position3f( x0, y0, 0.0f );
			meshBuilder.AdvanceVertex();

			meshBuilder.Color4ub( drawColor.r(), drawColor.g(), drawColor.b(), drawColor.a() );
			meshBuilder.TexCoord2f( 0, 0.0f, 0.0f );
			meshBuilder.Position3f( x1, y1, 0.0f );
			meshBuilder.AdvanceVertex();

			meshBuilder.Color4ub( drawColor.r(), drawColor.g(), drawColor.b(), drawColor.a() );
			meshBuilder.TexCoord2f( 0, 0.0f, 0.0f );
			meshBuilder.Position3f( x2, y2, 0.0f );
			meshBuilder.AdvanceVertex();
		}

		meshBuilder.End();
		m_pMesh->Draw();
	}
	) );
}

//-----------------------------------------------------------------------------
//-----------------------------------------------------------------------------
void CUI_Canvas::DrawFilledWedge( const Vector2D& vPos, float flRadius, float flStartAngle, float flAngleDelta, const Color& drawColor )
{
	CUI_CanvasRenderer *pRenderer = m_pRenderer;
	if ( !pRenderer )
		return;

	Vector2D vPosCopy = vPos;
	Color colorCopy = drawColor;

	EnqueueCommand( MakeDrawCommand(
		[ = ]( IMatRenderContext *pRenderContext )
	{
		int nNumTriangles = CANVAS_CIRCLE_POINT_COUNT;

		const float flUIScaleX = pRenderer->GetUIScaleX();
		const float flUIScaleY = pRenderer->GetUIScaleY();

		IMesh* m_pMesh = pRenderContext->GetDynamicMesh( true, NULL, NULL, pRenderer->m_WhiteMaterial );
		CMeshBuilder meshBuilder;
		meshBuilder.Begin( m_pMesh, MATERIAL_TRIANGLES, nNumTriangles * 3 );

		float x0 = pRenderer->GetUIScaleX() * vPos.x;
		float y0 = pRenderer->GetUIScaleX() * vPos.y;

		float flAngleIncrement = flAngleDelta / ( nNumTriangles - 1 );
		for ( int i = 0; i < nNumTriangles; ++i )
		{
			float x1 = pRenderer->GetUIScaleX() * ( vPosCopy.x + flRadius * cos( flStartAngle + i * flAngleIncrement ) );;
			float y1 = pRenderer->GetUIScaleY() * ( vPosCopy.y + flRadius * sin( flStartAngle + i * flAngleIncrement ) );

			float x2 = pRenderer->GetUIScaleX() * ( vPosCopy.x + flRadius * cos( flStartAngle + (i+1) * flAngleIncrement ) );;
			float y2 = pRenderer->GetUIScaleY() * ( vPosCopy.y + flRadius * sin( flStartAngle + (i+1) * flAngleIncrement ) );

			meshBuilder.Color4ub( drawColor.r()*0.5, drawColor.g()*0.5, drawColor.b()*0.5, drawColor.a() );
			meshBuilder.TexCoord2f( 0, 0.0f, 0.0f );
			meshBuilder.Position3f( x0, y0, 0.0f );
			meshBuilder.AdvanceVertex();

			meshBuilder.Color4ub( drawColor.r(), drawColor.g(), drawColor.b(), drawColor.a() );
			meshBuilder.TexCoord2f( 0, 0.0f, 0.0f );
			meshBuilder.Position3f( x1, y1, 0.0f );
			meshBuilder.AdvanceVertex();

			meshBuilder.Color4ub( drawColor.r(), drawColor.g(), drawColor.b(), drawColor.a() );
			meshBuilder.TexCoord2f( 0, 0.0f, 0.0f );
			meshBuilder.Position3f( x2, y2, 0.0f );
			meshBuilder.AdvanceVertex();
		}

		meshBuilder.End();
		m_pMesh->Draw();
	}
	) );
}

//-----------------------------------------------------------------------------
//-----------------------------------------------------------------------------
void CUI_Canvas::DrawLineCircle( const Vector2D& vPos, float flRadius, const Color& drawColor )
{
	CUI_CanvasRenderer *pRenderer = m_pRenderer;
	if ( !pRenderer )
		return;

	EnqueueCommand( MakeDrawCommand(
		[ = ]( IMatRenderContext *pRenderContext )
	{
		const float flUIScaleX = pRenderer->GetUIScaleX();
		const float flUIScaleY = pRenderer->GetUIScaleY();

		const int nPointCount = CANVAS_CIRCLE_POINT_COUNT;

		IMesh* m_pMesh = pRenderContext->GetDynamicMesh( true, NULL, NULL, pRenderer->m_WhiteMaterial );
		CMeshBuilder meshBuilder;
		meshBuilder.Begin( m_pMesh, MATERIAL_LINE_LOOP, nPointCount + 1 );

		// start
		meshBuilder.Color4ub( drawColor.r(), drawColor.g(), drawColor.b(), drawColor.a() );
		meshBuilder.TexCoord2f( 0, 0.0f, 0.0f );
		meshBuilder.Position3f( pRenderer->GetUIScaleX() * ( vPos.x + flRadius ), pRenderer->GetUIScaleX() * vPos.y, 0.0f );
		meshBuilder.AdvanceVertex();

		for ( int i = 1; i < nPointCount; ++i )
		{
			const float flTheta = i * 2 * M_PI / nPointCount;

			meshBuilder.Color4ub( drawColor.r(), drawColor.g(), drawColor.b(), drawColor.a() );
			meshBuilder.TexCoord2f( 0, 0.0f, 0.0f );
			meshBuilder.Position3f( pRenderer->GetUIScaleX() * ( vPos.x + flRadius * cos( flTheta ) ), pRenderer->GetUIScaleY() * ( vPos.y + flRadius * sin( flTheta ) ), 0.0f );
			meshBuilder.AdvanceVertex();
		}

		// back to start
		meshBuilder.Color4ub( drawColor.r(), drawColor.g(), drawColor.b(), drawColor.a() );
		meshBuilder.TexCoord2f( 0, 0.0f, 0.0f );
		meshBuilder.Position3f( pRenderer->GetUIScaleX() * ( vPos.x + flRadius ), pRenderer->GetUIScaleX() * vPos.y, 0.0f );
		meshBuilder.AdvanceVertex();

		meshBuilder.End();
		m_pMesh->Draw();
	}
	) );
}
