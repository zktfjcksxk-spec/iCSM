class CUI_Canvas_DrawPolyCommand : public CUI_Canvas_DrawCommand
{
public:
	CUI_CanvasRenderer *m_pRenderer;
	CUtlVector< Vector2D > m_vPoints;
	CUtlVector< Color > m_vColors;

	CUI_Canvas_DrawPolyCommand( CUI_CanvasRenderer *pRenderer, int nNumPoints, const Vector2D *pPoints, const Color *pColors )
	{
		m_pRenderer = pRenderer;
		m_vPoints.AddMultipleToTail( nNumPoints, pPoints );
		m_vColors.AddMultipleToTail( nNumPoints, pColors );
	}

	CUI_Canvas_DrawPolyCommand( CUI_CanvasRenderer *pRenderer, int nNumPoints, const Vector2D *pPoints, const Color &color )
	{
		m_pRenderer = pRenderer;
		m_vPoints.AddMultipleToTail( nNumPoints, pPoints );
		FOR_EACH_VEC( m_vPoints, i )
		{
			m_vColors.AddToTail( color );
		}
	}

	virtual void Execute( IMatRenderContext *pRenderContext )
	{
		const float flUIScaleX = m_pRenderer->GetUIScaleX();
		const float flUIScaleY = m_pRenderer->GetUIScaleY();

		int nNumTris = m_vPoints.Count() - 2;
		IMesh* m_pMesh = pRenderContext->GetDynamicMesh( true, NULL, NULL, m_pRenderer->m_WhiteMaterial );
		CMeshBuilder meshBuilder;
		meshBuilder.Begin( m_pMesh, MATERIAL_TRIANGLES, nNumTris * 3 );

		for ( int i = 0; i < nNumTris; i++ )
		{
			meshBuilder.Color4ub( m_vColors[ 0 ].r(), m_vColors[ 0 ].g(), m_vColors[ 0 ].b(), m_vColors[ 0 ].a() );
			meshBuilder.TexCoord2f( 0, 0.0f, 0.0f );
			meshBuilder.Position3f( m_vPoints[ 0 ].x * flUIScaleX, m_vPoints[ 0 ].y * flUIScaleY, 0.0f );
			meshBuilder.AdvanceVertex();

			meshBuilder.Color4ub( m_vColors[ i+1 ].r(), m_vColors[ i+1 ].g(), m_vColors[ i+1 ].b(), m_vColors[ i+1 ].a() );
			meshBuilder.TexCoord2f( 0, 0.0f, 0.0f );
			meshBuilder.Position3f( m_vPoints[ i+1 ].x * flUIScaleX, m_vPoints[ i+1 ].y * flUIScaleY, 0.0f );
			meshBuilder.AdvanceVertex();

			meshBuilder.Color4ub( m_vColors[ i+2 ].r(), m_vColors[ i+2 ].g(), m_vColors[ i+2 ].b(), m_vColors[ i+2 ].a() );
			meshBuilder.TexCoord2f( 0, 0.0f, 0.0f );
			meshBuilder.Position3f( m_vPoints[ i+2 ].x * flUIScaleX, m_vPoints[ i+2 ].y * flUIScaleY, 0.0f );
			meshBuilder.AdvanceVertex();
		}

		meshBuilder.End();
		m_pMesh->Draw();
	}
};

void CUI_Canvas::DrawPoly( int nPointCount, const Vector2D *pPoints, const Color *pColors )
{
	EnqueueCommand( new CUI_Canvas_DrawPolyCommand( m_pRenderer, nPointCount, pPoints, pColors ) );
}

void CUI_Canvas::DrawPoly( int nPointCount, const Vector2D *pPoints, const Color &color )
{
	EnqueueCommand( new CUI_Canvas_DrawPolyCommand( m_pRenderer, nPointCount, pPoints, color ) );
}

//-----------------------------------------------------------------------------
//-----------------------------------------------------------------------------
void CUI_Canvas::DrawThickLine( const Vector2D &v0, const Vector2D &v1, float flThickness, const Color &drawColor )
{
	Vector2D vDir = v1 - v0;
	vDir.NormalizeInPlace();

	const Vector2D vOrthogonal( vDir.y, -vDir.x );
	const Vector2D vHalfThick = flThickness * vOrthogonal * 0.5f;

	Vector2D polyLine[ 4 ] = {
		v0 - vHalfThick,
		v0 + vHalfThick,
		v1 + vHalfThick,
		v1 - vHalfThick
	};
	DrawPoly( V_ARRAYSIZE( polyLine ), polyLine, drawColor );
}

//-----------------------------------------------------------------------------
//-----------------------------------------------------------------------------
void CUI_Canvas::DrawThickLinePoints( int nNumPoints, const Vector2D *pPoints, float flThickness, const Color &drawColor )
{
	int nNumThickLines = nNumPoints - 1;

	DrawFilledCircle( pPoints[0], flThickness * 0.5f, drawColor );
	for ( int i = 0; i < nNumThickLines; i++ )
	{
		Vector2D vDir = pPoints[ i + 1 ] - pPoints[ i ];
		vDir.NormalizeInPlace();

		const Vector2D vOrthogonal( vDir.y, -vDir.x );
		const Vector2D vHalfThick = flThickness * vOrthogonal * 0.5f;

		Vector2D polyLine[ 4 ] = {
			pPoints[ i ] - vHalfThick,
			pPoints[ i ] + vHalfThick,
			pPoints[ i + 1 ] + vHalfThick,
			pPoints[ i + 1 ] - vHalfThick
		};
		DrawPoly( V_ARRAYSIZE( polyLine ), polyLine, drawColor );
		DrawFilledCircle( pPoints[ i + 1 ], flThickness * 0.5f, drawColor );
	}

}


