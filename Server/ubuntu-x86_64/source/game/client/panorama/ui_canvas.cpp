class CUI_Canvas_DrawCommand
{
public:
	CUI_Canvas_DrawCommand* m_pNext;
	CUI_Canvas_DrawCommand() : m_pNext( nullptr ) {}
	virtual ~CUI_Canvas_DrawCommand() {}
	virtual void Execute( IMatRenderContext* pRenderContext ) = 0;

private:
	CUI_Canvas_DrawCommand( const CUI_Canvas_DrawCommand& );
	CUI_Canvas_DrawCommand& operator=( const CUI_Canvas_DrawCommand& );
};

template <typename T>
class CUI_Canvas_DrawCommandLambda : public CUI_Canvas_DrawCommand
{
public:
	T drawCommand;
	CUI_Canvas_DrawCommandLambda( const T& fn )
		: drawCommand( fn )
	{
	}
	virtual void Execute( IMatRenderContext* pRenderContext )
	{
		drawCommand( pRenderContext );
	}
};

template <typename T>
CUI_Canvas_DrawCommandLambda<T>* MakeDrawCommand( const T& fn )
{
	return new CUI_Canvas_DrawCommandLambda<T>( fn );
}

//-----------------------------------------------------------------------------
//-----------------------------------------------------------------------------
CUI_Canvas::CUI_Canvas( CPanel2D *pParent, const char *pchID )
	: CRenderPanel( pParent, pchID, ePanelFlags_DontFireOnLoad )
	, m_bHasLayoutTraversed( false )
{
	// We must uniqueify the world name
	static int s_nIndex = 1;
	char pAutoGeneratedID[128];
	if ( !pchID || !pchID[0] )
	{
		pchID = "unknown_canvas_panel";
	}

	V_sprintf_safe( pAutoGeneratedID, "%s_%d", pchID, s_nIndex );
	++s_nIndex;
	pchID = pAutoGeneratedID;

	m_pRenderer = NULL;

	RegisterForReadyEvents( true );
	
	if ( !UIEngine()->BHaveEventHandlersRegisteredForType( CUI_Canvas::GetPanelSymbol() ) )
	{
		RegisterEventHandlerOnPanelType( ReadyForDisplay(), &CUI_Canvas::OnReadyForDisplay );
		RegisterEventHandlerOnPanelType( UnreadyForDisplay(), &CUI_Canvas::OnUnreadyForDisplay );
	}

	SetAcceptsFocus( true );
	SetAcceptsInput( true );

 	if ( g_pPanoramaUIEngine )
 	{
 		g_pPanoramaUIEngine->AddDeviceDependentObject( this );
 	}

	Init();
}

//-----------------------------------------------------------------------------
//-----------------------------------------------------------------------------
CUI_Canvas::~CUI_Canvas()
{
	ClearCommandQueue();

 	if ( g_pPanoramaUIEngine )
 	{
 		g_pPanoramaUIEngine->RemoveDeviceDependentObject( this );
 	}

	if ( m_pRenderer )
		m_pRenderer->Release();

	m_pRenderer = nullptr;
}

//-----------------------------------------------------------------------------
//-----------------------------------------------------------------------------
void CUI_Canvas::Init()
{
	m_pRenderer = new CUI_CanvasRenderer();
	SetRenderThreadCallback( m_pRenderer, k_ERenderCallbackFlagsRenderTargetMode );

	m_pCommandQueue = nullptr;
	m_pCommandQueueTail = &m_pCommandQueue;

	m_bClearQueue = false;
	m_bScalingDisabled = false;

//	m_flLastTime = 0.0f;

	m_bAllowDrawing = false;

	m_bDrawing = false;

	m_flLastMouseX = 0.0f;
	m_flLastMouseY = 0.0f;

	SetDrawSize( 10.0f );
	SetDrawColor( Color( 255, 0, 0, 255 ) );

	m_nPanoramaSurfaceWidth = 0;
	m_nPanoramaSurfaceHeight = 0;
}

//-----------------------------------------------------------------------------
//-----------------------------------------------------------------------------
void CUI_Canvas::ClearCommandQueue( void )
{
	CUI_Canvas_DrawCommand *pCmd = m_pCommandQueue;
	m_pCommandQueue = nullptr;
	while ( pCmd != nullptr )
	{
		CUI_Canvas_DrawCommand * const pNext = pCmd->m_pNext;
		delete pCmd;
		pCmd = pNext;
	}
	m_pCommandQueueTail = &m_pCommandQueue;
	m_bClearQueue = true;
}

//-----------------------------------------------------------------------------
//-----------------------------------------------------------------------------
void CUI_Canvas::EnqueueCommand( CUI_Canvas_DrawCommand *pCmd )
{
	if ( m_pRenderer == nullptr )
	{
		delete pCmd;
		return;
	}

	*m_pCommandQueueTail = pCmd;
	m_pCommandQueueTail = &pCmd->m_pNext;
	SetRepaint( EPanelRepaint::k_EPanelRepaintFull );

	m_pRenderer->SetNeedsRedraw( true );
}

//-----------------------------------------------------------------------------
//-----------------------------------------------------------------------------
void CUI_Canvas::SetScalingDisabled( bool bDisabled )
{
	m_bScalingDisabled = bDisabled;
	SetRepaint( EPanelRepaint::k_EPanelRepaintFull );
}

