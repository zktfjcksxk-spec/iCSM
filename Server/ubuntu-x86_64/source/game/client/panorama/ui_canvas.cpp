void CUI_Canvas::OnMouseMove( float flMouseX, float flMouseY )
{
	float flX, flY;

	// match scaling/space of drawing fn coords
	if ( m_bScalingDisabled )
	{
		flX = flMouseX;
		flY = flMouseY;
	}
	else
	{
		// DrawThickLinePoly scales( if enabled ) by GetActualUIScale, so apply inverse here
		flX = flMouseX / GetActualUIScaleX();
		flY = flMouseY / GetActualUIScaleY();
	}

	if ( m_bDrawing )
	{
		Vector2D aLinePoly[ 2 ];

		aLinePoly[ 0 ] = Vector2D( m_flLastMouseX, m_flLastMouseY );
		aLinePoly[ 1 ] = Vector2D( flX, flY );

		DrawThickLinePoints( 2, aLinePoly, m_flDrawSize, m_drawColor );
	}

	m_flLastMouseX = flX;
 	m_flLastMouseY = flY;


	return BaseClass::OnMouseMove( flMouseX, flMouseY );
}

