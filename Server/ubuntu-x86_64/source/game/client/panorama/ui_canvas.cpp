static float UI_GetAutoPlayTime( void )
{
	static int s_prevTicks = 0;
	static float s_time = 0.0f;

	int ticks = Plat_MSTime();

	// limit delta so that float time doesn't overflow
	if ( s_prevTicks == 0 )
	{
		s_prevTicks = ticks;
	}

	s_time += ( ticks - s_prevTicks ) / 1000.0f;
	s_prevTicks = ticks;

	return s_time;
}

