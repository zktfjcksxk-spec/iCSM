inline const CatalogEntry *FindCatalog(int definition, int paint)
{
    unsigned first = 0, last = sizeof(Catalog) / sizeof(Catalog[0]);
    while (first < last)
    {
        unsigned middle = first + (last - first) / 2;
        const CatalogEntry &entry = Catalog[middle];
        if (entry.definition < definition || (entry.definition == definition && entry.paint < paint))
            first = middle + 1;
        else last = middle;
    }
    return first < sizeof(Catalog) / sizeof(Catalog[0]) &&
        Catalog[first].definition == definition && Catalog[first].paint == paint ? &Catalog[first] : NULL;
}
